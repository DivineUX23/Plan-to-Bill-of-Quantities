"""Export takeoff quantities to formatted Excel spreadsheet.

Organises quantities into standard takeoff bill sections with audit calculation traces.
"""

from __future__ import annotations

import io
import openpyxl
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

from ..models import Project
from ..schemas import Takeoff


def export_takeoff_xlsx(project: Project, takeoff: Takeoff) -> bytes:
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Takeoff Summary"

    # Styling palette
    NAVY = "002B5C"
    WHITE = "FFFFFF"
    LIGHT_GRAY = "F8F9FA"
    BORDER_GRAY = "D1D5DB"

    font_title = Font(name="Arial", size=14, bold=True, color=WHITE)
    font_subtitle = Font(name="Arial", size=10, italic=True, color=WHITE)
    font_group = Font(name="Arial", size=11, bold=True, color=NAVY)
    font_header = Font(name="Arial", size=10, bold=True, color=WHITE)
    font_bold = Font(name="Arial", size=10, bold=True)
    font_regular = Font(name="Arial", size=10)
    font_trace = Font(name="Arial", size=8, italic=True, color="555555")

    fill_title = PatternFill(start_color=NAVY, end_color=NAVY, fill_type="solid")
    fill_header = PatternFill(start_color="1E3A8A", end_color="1E3A8A", fill_type="solid")
    fill_group = PatternFill(start_color="E0E7FF", end_color="E0E7FF", fill_type="solid")
    fill_zebra = PatternFill(start_color="F9FAFB", end_color="F9FAFB", fill_type="solid")

    thin_border = Border(
        left=Side(style="thin", color=BORDER_GRAY),
        right=Side(style="thin", color=BORDER_GRAY),
        top=Side(style="thin", color=BORDER_GRAY),
        bottom=Side(style="thin", color=BORDER_GRAY),
    )

    # Header banner
    ws.merge_cells("A1:E1")
    ws["A1"] = f"PLANTOBOQ TAKEOFF - {project.name.upper()}"
    ws["A1"].font = font_title
    ws["A1"].fill = fill_title
    ws["A1"].alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[1].height = 28

    ws.merge_cells("A2:E2")
    loc = f" | Location: {project.location}" if project.location else ""
    client = f"Client: {project.client}" if project.client else "Client: -"
    ws["A2"] = f"{client}{loc} | Generated by PlanToBOQ Taking-off Engine"
    ws["A2"].font = font_subtitle
    ws["A2"].fill = fill_title
    ws["A2"].alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[2].height = 18

    # Table columns
    row_idx = 4
    headers = ["Item Ref", "Description & Calculation Trace", "Qty", "Unit", "Notes"]
    for col_idx, h in enumerate(headers, 1):
        cell = ws.cell(row=row_idx, column=col_idx, value=h)
        cell.font = font_header
        cell.fill = fill_header
        cell.alignment = Alignment(horizontal="center" if col_idx in (3, 4) else "left", vertical="center")
    ws.row_dimensions[row_idx].height = 22

    item_counter = 1
    for group in takeoff.groups:
        row_idx += 1
        ws.merge_cells(start_row=row_idx, start_column=1, end_row=row_idx, end_column=5)
        cell = ws.cell(row=row_idx, column=1, value=group.title.upper())
        cell.font = font_group
        cell.fill = fill_group
        ws.row_dimensions[row_idx].height = 20

        for item in group.items:
            row_idx += 1
            ws.cell(row=row_idx, column=1, value=f"{item_counter}").font = font_bold
            ws.cell(row=row_idx, column=2, value=item.description).font = font_bold
            qty_cell = ws.cell(row=row_idx, column=3, value=item.quantity)
            qty_cell.font = font_bold
            qty_cell.number_format = "#,##0.00" if item.unit != "nr" else "#,##0"
            qty_cell.alignment = Alignment(horizontal="right")
            unit_cell = ws.cell(row=row_idx, column=4, value=item.unit)
            unit_cell.font = font_regular
            unit_cell.alignment = Alignment(horizontal="center")

            # Border for row
            for c in range(1, 6):
                ws.cell(row=row_idx, column=c).border = thin_border

            # Calculation trace lines
            if item.trace:
                for tr in item.trace:
                    row_idx += 1
                    ws.cell(row=row_idx, column=2, value=f"  → {tr}").font = font_trace
                    for c in range(1, 6):
                        ws.cell(row=row_idx, column=c).border = thin_border

            item_counter += 1

    # Adjust column widths
    ws.column_dimensions["A"].width = 10
    ws.column_dimensions["B"].width = 52
    ws.column_dimensions["C"].width = 14
    ws.column_dimensions["D"].width = 10
    ws.column_dimensions["E"].width = 24

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()
